"""Генерирует payload.rc и payload_index.h из содержимого dist.

Запуск: python gen_payload.py <dist> <output_dir>
"""
import os
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_payload.py <dist> <output_dir>", file=sys.stderr)
        return 2

    dist = os.path.abspath(sys.argv[1])
    out = os.path.abspath(sys.argv[2])
    skip = {"deepseektraysetup.exe"}

    files = []
    for root, _dirs, names in os.walk(dist):
        for name in names:
            full = os.path.join(root, name)
            rel = os.path.relpath(full, dist)
            first = rel.split(os.sep)[0].lower()
            # страховка: не затягивать вложенную установку в payload
            if first == "deepseektray":
                continue
            if rel.lower() in skip or rel.lower().endswith(".pdb"):
                continue
            files.append((rel, full))
    files.sort(key=lambda item: item[0].lower())

    rc_lines = ["// generated by gen_payload.py, do not edit"]
    h_lines = [
        "// generated by gen_payload.py, do not edit",
        "#pragma once",
        "struct PayloadFile { int id; const wchar_t *path; };",
        "static const PayloadFile kPayload[] = {",
    ]

    for index, (rel, full) in enumerate(files):
        rid = 1000 + index
        rc_lines.append('{} RCDATA "{}"'.format(rid, full.replace("\\", "\\\\")))
        h_lines.append('    {{ {}, L"{}" }},'.format(rid, rel.replace("\\", "\\\\")))

    h_lines.append("};")
    h_lines.append("static const int kPayloadCount = {};".format(len(files)))

    with open(os.path.join(out, "payload.rc"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(rc_lines) + "\n")

    with open(os.path.join(out, "payload_index.h"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(h_lines) + "\n")

    print("payload: {} files, {:.1f} MB".format(
        len(files), sum(os.path.getsize(p) for _r, p in files) / (1024 * 1024)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
